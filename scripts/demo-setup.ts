/** One-command local demo setup for ZCTA 85004 (prototype shortcut; harden later).
 *
 * Writes `.env` enabling every native workbench on this machine, installs the
 * prepared flood and housing catalogs into the dev store, and opens the
 * budget gate with a local zero-external-cost review (max 7 days, re-run to
 * renew). Refuses to run while the API is listening because the dev store is
 * written directly.
 *
 *   corepack pnpm exec tsx scripts/demo-setup.ts
 */
import { copyFile, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { createConnection } from "node:net";
import { resolve } from "node:path";
import { FileStore } from "../apps/api/src/store";
import { FloodCatalog, installFloodCatalog } from "../apps/api/src/flood-catalog";
import {
  HousingCatalog,
  installHousingCatalog,
} from "../apps/api/src/housing-catalog";
import { recordBudgetCostReview } from "../apps/api/src/budget";
import { budgetReviewFixtureInput } from "../apps/api/src/budget-test-fixture";

const root = resolve(".");
const local = (path: string) => resolve(root, ".local", path);
const paths = {
  store: local("api-state.json"),
  flood: local("flood/catalog-method-1.1-qa.json"),
  housing: local("housing/catalog-fy2026-v1"),
  traffic: local("traffic/registry.json"),
  workforcePack: local(
    "workforce/packs/672159c4348ad1873430df027204a6ec4651f67ce6e16dcdb526ea2ef63b830b.json",
  ),
  accessibilityPack: local(
    "accessibility/packs/jobs-954a3dc7e2ae7fd97e702a004ca27fb473c195507c4bdb6506a2aa6959590323.json",
  ),
  boundary: local(
    "workforce/boundaries/boundary-04-3ff638ba0e6b8676157cd70eb1e6213a48017d658760567ec264a9455d5fa7de.json",
  ),
  manifest: local("routing/active/manifest.json"),
  mediaImage: local("qa/media/runtime-image.id"),
  mediaRenderer: resolve(root, "dist/media-render"),
};

const portOpen = (port: number) =>
  new Promise<boolean>((done) => {
    const socket = createConnection({ host: "127.0.0.1", port });
    socket.once("connect", () => (socket.destroy(), done(true)));
    socket.once("error", () => done(false));
  });

if (await portOpen(3001))
  throw new Error("Stop the API (port 3001) first; this script writes the dev store directly.");
for (const [name, path] of Object.entries(paths))
  if (name !== "store" && !existsSync(path))
    throw new Error(`Missing demo prerequisite ${name}: ${path}`);
if (!(await portOpen(8002)))
  console.warn("Routing (Valhalla) is not on :8002 — run `docker start urban-planning-routing`.");

const capacity = (label: string) => [
  `${label}_CAPACITY_ENVIRONMENT=local-development`,
  `${label}_CAPACITY_STATEMENT=Local demo workstation; existing hardware, no paid provider.`,
];
const mediaImage = (await readFile(paths.mediaImage, "utf8")).trim();
// Carry over an existing Census key from .env.local without printing it.
const census = existsSync(".env.local")
  ? (await readFile(".env.local", "utf8"))
      .split("\n")
      .find((line) => line.startsWith("CENSUS_API_KEY="))
  : undefined;
const env = [
  "# Generated by scripts/demo-setup.ts — local demo only.",
  "NODE_ENV=development",
  "PORT=3001",
  "HOST=127.0.0.1",
  "APP_ORIGIN=http://localhost:5173",
  ...(census ? [census] : []),
  `FLOOD_CATALOG=${paths.flood}`,
  `HOUSING_CATALOG=${paths.housing}`,
  "TRAFFIC_ENABLED=true",
  `TRAFFIC_NETWORK_REGISTRY=${paths.traffic}`,
  ...capacity("TRAFFIC"),
  "WORKFORCE_ENABLED=true",
  `WORKFORCE_PACK_PATH=${paths.workforcePack}`,
  `WORKFORCE_BOUNDARY_PATH=${paths.boundary}`,
  `WORKFORCE_MANIFEST_PATH=${paths.manifest}`,
  ...capacity("WORKFORCE"),
  "ACCESSIBILITY_ENABLED=true",
  `ACCESSIBILITY_PACK_PATH=${paths.accessibilityPack}`,
  `ACCESSIBILITY_BOUNDARY_PATH=${paths.boundary}`,
  `ACCESSIBILITY_MANIFEST_PATH=${paths.manifest}`,
  ...capacity("ACCESSIBILITY"),
  "GIS_ENABLED=true",
  ...capacity("GIS"),
  "MEDIA_ENABLED=true",
  `MEDIA_IMAGE_ID=${mediaImage}`,
  `MEDIA_RENDERER_DIRECTORY=${paths.mediaRenderer}`,
  ...capacity("MEDIA"),
  "",
].join("\n");
await writeFile(".env", env, { mode: 0o600 });
console.log("Wrote .env");

const sqlite = `${paths.store}.sqlite`;
if (existsSync(sqlite)) {
  const backup = `${sqlite}.bak-${new Date().toISOString().replace(/[:.]/g, "-")}`;
  await copyFile(sqlite, backup);
  console.log(`Backed up dev store to ${backup}`);
}
const store = new FileStore(paths.store);
try {
  console.log("Flood catalog:", await installFloodCatalog(store, new FloodCatalog(paths.flood)));
  console.log("Housing catalog:", await installHousingCatalog(store, new HousingCatalog(paths.housing)));
  await store.transaction((state) => {
    const now = new Date();
    const monthEnd = Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + 1, 1);
    state.budget.policy.paidOperationsPaused = false;
    recordBudgetCostReview(
      state.budget,
      {
        ...budgetReviewFixtureInput(state.budget, now),
        expiresAt: new Date(
          Math.min(now.getTime() + 7 * 86_400_000 - 60_000, monthEnd),
        ).toISOString(),
        scopeStatement:
          "Local demo workstation. Native SUMO, Valhalla, GDAL and media containers run on existing hardware; no paid external provider is called.",
      },
      "demo-setup",
      now,
    );
  });
  console.log("Budget gate open (review valid up to 7 days; re-run to renew).");
} finally {
  await store.close();
}
console.log("Done. Start the app with: corepack pnpm dev");
